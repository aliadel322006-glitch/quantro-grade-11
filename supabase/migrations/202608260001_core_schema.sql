create or replace function private.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  requested_role text;
  safe_role public.app_role;
begin
  requested_role := new.raw_app_meta_data ->> 'app_role';
  safe_role := case requested_role
    when 'teacher' then 'teacher'::public.app_role
    when 'admin' then 'admin'::public.app_role
    else 'student'::public.app_role
  end;

  insert into public.profiles (user_id, role, display_name, preferred_locale)
  values (
    new.id,
    safe_role,
    nullif(btrim(new.raw_user_meta_data ->> 'display_name'), ''),
    case when new.raw_user_meta_data ->> 'preferred_locale' = 'ar'
      then 'ar'::public.locale_code else 'en'::public.locale_code end
  )
  on conflict (user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function private.handle_new_auth_user();

create or replace function private.validate_class_owner()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  owner_role public.app_role;
begin
  select p.role into owner_role from public.profiles p where p.user_id = new.teacher_id;
  if owner_role is null or owner_role not in ('teacher', 'admin') then
    raise exception using errcode = '23514', message = 'class owner must have teacher or admin role';
  end if;

  if new.status = 'archived' and new.archived_at is null then
    new.archived_at := statement_timestamp();
  elsif new.status = 'active' then
    new.archived_at := null;
  end if;
  return new;
end;
$$;

