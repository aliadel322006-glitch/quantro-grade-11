create or replace function private.protect_lesson_version()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'DELETE' then
    if old.status <> 'draft' then
      raise exception using errcode = '55000', message = 'published lesson versions cannot be deleted';
    end if;
    return old;
  end if;

  if tg_op = 'INSERT' and new.status <> 'draft'
     and coalesce(current_setting('app.lesson_publish_context', true), '') <> 'on' then
    raise exception using errcode = '55000', message = 'lesson versions must be published through the publish workflow';
  end if;

  if tg_op = 'UPDATE' and old.status <> 'draft' then
    if new.lesson_id is distinct from old.lesson_id
       or new.version is distinct from old.version
       or new.content is distinct from old.content
       or new.content_hash is distinct from old.content_hash
       or new.source_version_id is distinct from old.source_version_id
       or new.created_by is distinct from old.created_by
       or new.created_at is distinct from old.created_at then
      raise exception using errcode = '55000', message = 'published lesson version content is immutable';
    end if;
    if old.status = 'archived' and new.status <> 'archived' then
      raise exception using errcode = '55000', message = 'archived lesson versions cannot be reactivated';
    end if;
    if old.status = 'published' and new.status not in ('published', 'archived') then
      raise exception using errcode = '55000', message = 'invalid lesson version lifecycle transition';
    end if;
  end if;

  if tg_op = 'UPDATE' and old.status = 'draft' and new.status <> old.status
     and coalesce(current_setting('app.lesson_publish_context', true), '') <> 'on' then
    raise exception using errcode = '55000', message = 'lesson versions must be published through the publish workflow';
  end if;

  if tg_op = 'INSERT' or new.content is distinct from old.content then
    new.content_hash := encode(extensions.digest(convert_to(new.content::text, 'UTF8'), 'sha256'), 'hex');
  end if;
  new.updated_at := statement_timestamp();
  return new;
end;
$$;

create trigger lesson_versions_protect
  before insert or update or delete on public.lesson_versions
  for each row execute function private.protect_lesson_version();

create or replace function private.validate_assignment()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  version_status public.lesson_version_status;
begin
  if tg_op = 'UPDATE' then
    if new.class_id is distinct from old.class_id
       or new.lesson_version_id is distinct from old.lesson_version_id then
      raise exception using errcode = '55000', message = 'assignment class and pinned lesson version are immutable';
    end if;
  end if;

  select lv.status into version_status
  from public.lesson_versions lv
  where lv.id = new.lesson_version_id;

  if tg_op = 'INSERT' and version_status <> 'published' then
    raise exception using errcode = '23514', message = 'new assignments must pin a currently published lesson version';
  end if;
  return new;
end;
$$;

