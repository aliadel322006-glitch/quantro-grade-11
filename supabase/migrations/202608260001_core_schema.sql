create or replace function private.validate_learning_event()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  assignment_class_id uuid;
  pinned_version_id uuid;
  current_class_status public.class_status;
begin
  select a.class_id, a.lesson_version_id, c.status
    into assignment_class_id, pinned_version_id, current_class_status
  from public.assignments a
  join public.classes c on c.id = a.class_id
  where a.id = new.assignment_id;

  if assignment_class_id is null then
    raise exception using errcode = '23503', message = 'assignment does not exist';
  end if;
  if pinned_version_id <> new.lesson_version_id then
    raise exception using errcode = '23514', message = 'event lesson version does not match assignment';
  end if;
  if current_class_status <> 'active' then
    raise exception using errcode = '23514', message = 'events cannot be added to an archived class';
  end if;
  if not exists (
    select 1 from public.memberships m
    where m.class_id = assignment_class_id
      and m.user_id = new.student_id
      and m.member_role = 'student'
  ) then
    raise exception using errcode = '42501', message = 'student is not a member of the assigned class';
  end if;
  return new;
end;
$$;

